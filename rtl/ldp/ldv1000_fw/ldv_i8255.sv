//============================================================================
// ldv_i8255.sv -- Intel 8255 PPI, mode 0 only, for the LD-V1000 firmware model.
//
// Port of MAME i8255.cpp mode-0 paths (set_mode / write_mode0 / read_mode0 /
// read_pc / output_pc / set_pc_bit).  Mode 1/2 handshake is not modelled.
//   * Reset = control word 0x9B (all ports input), output latches cleared.
//   * A mode-set write clears all three output latches.
//   * A port-A/B write only latches when that port is an output; a port-C write
//     always latches.  Bit set/reset touches only the port-C latch.
//   * Reads: output port -> its latch, input port -> the pins (port C is split
//     per nibble); control register reads back.
//   * *_o are the PIN levels: latch where the port is an output, 0xFF where it
//     is an input (MAME's default "TTL inputs floating" tri-state callback).
// Bus strobes are 1-clk pulses generated by the caller at the end of a cycle.
//============================================================================
module ldv_i8255 (
    input             clk,
    input             reset_n,

    input             wr_stb,      // 1-clk: register write (uses waddr / wdata)
    input       [1:0] waddr,
    input       [7:0] wdata,
    input       [1:0] raddr,       // combinational read address
    output reg  [7:0] dout,

    input       [7:0] pa_i,
    input       [7:0] pb_i,
    input       [7:0] pc_i,
    output      [7:0] pa_o,
    output      [7:0] pb_o,
    output      [7:0] pc_o
);
    reg [7:0] ctrl;
    reg [7:0] la, lb, lc;

    wire a_in  = ctrl[4];
    wire b_in  = ctrl[1];
    wire cu_in = ctrl[3];
    wire cl_in = ctrl[0];

    assign pa_o = a_in ? 8'hFF : la;
    assign pb_o = b_in ? 8'hFF : lb;
    assign pc_o = {cu_in ? 4'hF : lc[7:4], cl_in ? 4'hF : lc[3:0]};

    always @(posedge clk) begin
        if (!reset_n) begin
            ctrl <= 8'h9B;
            la <= 8'h00; lb <= 8'h00; lc <= 8'h00;
        end else if (wr_stb) begin
            case (waddr)
                2'd0: if (!a_in) la <= wdata;
                2'd1: if (!b_in) lb <= wdata;
                2'd2: lc <= wdata;
                2'd3: if (wdata[7]) begin
                          ctrl <= wdata;
                          la <= 8'h00; lb <= 8'h00; lc <= 8'h00;
                      end else begin
                          lc[wdata[3:1]] <= wdata[0];
                      end
            endcase
        end
    end

    always @(*) begin
        case (raddr)
            2'd0:    dout = a_in ? pa_i : la;
            2'd1:    dout = b_in ? pb_i : lb;
            2'd2:    dout = {cu_in ? pc_i[7:4] : lc[7:4], cl_in ? pc_i[3:0] : lc[3:0]};
            default: dout = ctrl;
        endcase
    end
endmodule
